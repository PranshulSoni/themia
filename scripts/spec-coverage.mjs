// SPEC [S-NN] → test coverage matrix generator.
//
// Scans every widgets/**/SPEC.md + src/SPEC.md for [S-NN] behavior tags, then
// scans the test corpus (unit *.test.ts, e2e *.spec.ts, Rust *.rs) for tag
// citations. Emits docs/SPEC-COVERAGE.md.
//
// HONEST CAVEATS (read before trusting a "covered" cell):
//  - Tags are namespaced PER SPEC ([S-13] in folder/SPEC.md ≠ [S-13] in
//    src/SPEC.md), but citations in tests are bare `[S-NN]`. So a tag counted
//    "cited" may be cited for a DIFFERENT spec, so coverage is an UPPER bound.
//  - The reliable signal is the inverse: a tag whose number is cited NOWHERE in
//    the whole corpus is a definite gap. Those are listed per spec as "GAP".
//  - A behavior can be covered by an e2e/manual test that doesn't cite its tag.
//    The fix for both caveats is the convention: name tests after the tag they
//    pin (e.g. `[S-13]`, `s8_…`). This tool nudges toward that.
//
// Run: node scripts/spec-coverage.mjs   (writes docs/SPEC-COVERAGE.md)

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const TAG_RE = /\[S-(\d+)\]/g;

function walk(dir, pred, out = []) {
  let entries;
  try { entries = readdirSync(dir); } catch { return out; }
  for (const e of entries) {
    if (e === 'node_modules' || e === 'target' || e === '.git' || e === 'dist') continue;
    const p = join(dir, e);
    let s;
    try { s = statSync(p); } catch { continue; }
    if (s.isDirectory()) walk(p, pred, out);
    else if (pred(p)) out.push(p);
  }
  return out;
}

// 1. Collect tags per SPEC (with the one-line behavior text).
const specFiles = walk(ROOT, (p) => p.endsWith('SPEC.md')).sort();
const specs = [];
for (const f of specFiles) {
  const text = readFileSync(f, 'utf8');
  const lines = text.split(/\r?\n/);
  const tags = [];
  const seen = new Set();
  for (const line of lines) {
    // A tag DEFINITION is a list item starting with the tag (bold or plain):
    //   `- [S-01] …`  or  `- **[S-01]** …`. Inline references mid-sentence
    //   (e.g. "see ([S-07])") are intentionally NOT matched.
    const m = /^\s*[-*]\s*(?:\*\*)?\[S-(\d+)\](?:\*\*)?:?\s*(.*)/.exec(line);
    if (!m) continue;
    const num = Number(m[1]);
    if (seen.has(num)) continue;
    seen.add(num);
    const desc = m[2].replace(/\s+/g, ' ').slice(0, 90);
    tags.push({ num, desc });
  }
  if (tags.length) specs.push({ file: relative(ROOT, f).replace(/\\/g, '/'), tags });
}

// 2. Collect the set of tag NUMBERS cited anywhere in the test corpus.
const testFiles = walk(ROOT, (p) =>
  p.endsWith('.test.ts') || p.endsWith('.spec.ts') ||
  (p.endsWith('.rs') && /[\\/](tests?|src)[\\/]/.test(p)),
);
const citedNums = new Set();
for (const f of testFiles) {
  let text;
  try { text = readFileSync(f, 'utf8'); } catch { continue; }
  let m;
  TAG_RE.lastIndex = 0;
  while ((m = TAG_RE.exec(text))) {
    citedNums.add(Number(m[1]));
  }
}

// 3. Build the report.
let totalTags = 0;
let totalCited = 0;
const rows = [];
for (const spec of specs) {
  const gaps = [];
  let cited = 0;
  for (const t of spec.tags) {
    totalTags++;
    if (citedNums.has(t.num)) { cited++; totalCited++; }
    else gaps.push(t);
  }
  rows.push({ file: spec.file, total: spec.tags.length, cited, gaps });
}

const pct = (a, b) => (b === 0 ? '—' : `${Math.round((a / b) * 100)}%`);

let md = '';
md += '# SPEC [S-NN] → test coverage matrix\n\n';
md += '_Generated by `node scripts/spec-coverage.mjs`. Do not edit by hand._\n\n';
md += '**How to read this:** "cited" = the tag number appears in at least one\n';
md += 'test/spec/rust-test file. Tags are namespaced per SPEC but citations are\n';
md += 'bare `[S-NN]`, so "cited" is an UPPER bound (a cite may belong to another\n';
md += "spec's same-numbered tag). The trustworthy signal is the GAP list: a tag\n";
md += 'whose number is cited NOWHERE has no test pinning it. Close a gap by naming\n';
md += 'a test after the tag (`[S-NN]` in the title / `sNN_` for rust).\n\n';
md += `**Totals:** ${totalCited}/${totalTags} tags cited (${pct(totalCited, totalTags)}) across `;
md += `${specs.length} SPECs and ${testFiles.length} test files.\n\n`;
md += '| SPEC | tags | cited | coverage | gaps (uncited tag numbers) |\n';
md += '| --- | ---: | ---: | ---: | --- |\n';
for (const r of rows.sort((a, b) => (a.cited / a.total) - (b.cited / b.total))) {
  const gapList = r.gaps.length ? r.gaps.map((g) => `S-${String(g.num).padStart(2, '0')}`).join(', ') : '—';
  md += `| \`${r.file}\` | ${r.total} | ${r.cited} | ${pct(r.cited, r.total)} | ${gapList} |\n`;
}
md += '\n## Fully-uncited SPECs (no tag cited by any test, highest-priority)\n\n';
const dark = rows.filter((r) => r.cited === 0);
if (!dark.length) md += '_None: every SPEC has at least one cited tag._\n';
else for (const r of dark) md += `- \`${r.file}\` (${r.total} tags)\n`;

writeFileSync(join(ROOT, 'docs', 'SPEC-COVERAGE.md'), md);
console.log(`Wrote docs/SPEC-COVERAGE.md: ${totalCited}/${totalTags} tags cited (${pct(totalCited, totalTags)}), ${dark.length} fully-uncited SPECs.`);
