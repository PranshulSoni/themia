"""
Generate the icon picker's glyph table ([S-1800]) from the WinUI Gallery's icon list.

Source: microsoft/WinUI-Gallery, WinUIGallery/Samples/Iconography/IconsData.json (MIT, see
THIRD-PARTY-NOTICES.md): every Segoe Fluent Icons glyph with its name and search tags.

Writes src/Themia.Core/Icons/FluentIconData.g.cs: a plain C# table, so the app reads no file and
parses no JSON at run time (Native AOT clean). Tags are lower-cased, trimmed and de-duplicated; the
Gallery's "symbol-icon" marker (it says a Symbol enum value exists) is dropped as it means nothing
to a person searching.

Run after the Gallery's list changes:
    python scripts/fluent-icons.py [path-or-url-to-IconsData.json]
The generated file is checked in; the build does not run this.
"""

import json
import sys
import urllib.request
from pathlib import Path

DEFAULT_URL = "https://raw.githubusercontent.com/microsoft/WinUI-Gallery/main/WinUIGallery/Samples/Iconography/IconsData.json"
OUT = Path(__file__).resolve().parent.parent / "src" / "Themia.Core" / "Icons" / "FluentIconData.g.cs"
DROPPED_TAGS = {"symbol-icon"}


def load(source: str):
    if source.startswith("http"):
        with urllib.request.urlopen(source) as response:
            return json.loads(response.read().decode("utf-8"))
    return json.loads(Path(source).read_text(encoding="utf-8"))


def literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    source = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_URL
    entries = load(source)

    rows = []
    seen = set()
    for entry in entries:
        code = int(entry["Code"], 16)
        name = entry["Name"].strip()
        if not name or code in seen or not (0xE000 <= code <= 0xF8FF):
            raise SystemExit(f"unexpected entry: {entry!r}")
        seen.add(code)

        tags = []
        for tag in entry.get("Tags") or []:
            tag = " ".join(tag.strip().lower().split())
            if tag and tag not in DROPPED_TAGS and tag not in tags:
                tags.append(tag)

        rows.append((code, name, tags))

    rows.sort(key=lambda row: row[0])

    lines = [
        "// <auto-generated>",
        "// Generated by scripts/fluent-icons.py from microsoft/WinUI-Gallery",
        "// WinUIGallery/Samples/Iconography/IconsData.json (MIT License, Copyright (c) Microsoft",
        "// Corporation; see THIRD-PARTY-NOTICES.md). Do not edit by hand: run the script again.",
        "// </auto-generated>",
        "",
        "namespace Themia.Core.Icons;",
        "",
        "public static partial class FluentIcons",
        "{",
        f"    /// <summary>Every Segoe Fluent Icons glyph the WinUI Gallery lists ({len(rows)}), in code-point order.</summary>",
        "    private static readonly FluentIcon[] Data =",
        "    [",
    ]
    for code, name, tags in rows:
        tag_list = ", ".join(literal(tag) for tag in tags)
        lines.append(f"        new(0x{code:04X}, {literal(name)}, [{tag_list}]),")
    lines += ["    ];", "}", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\r\n")
    print(f"wrote {len(rows)} glyphs to {OUT}")


if __name__ == "__main__":
    main()
