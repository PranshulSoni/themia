using System.Text;
using Themia.Core.Localization;

namespace Themia.Core.Icons;

/// <summary>
/// [S-1800] One Segoe Fluent Icons glyph as the icon picker offers it.
/// </summary>
/// <param name="Code">The private-use code point (U+E700..U+F8FF).</param>
/// <param name="Name">The Gallery's PascalCase name, e.g. <c>GlobalNavButton</c>.</param>
/// <param name="Tags">Lower-case search words from the Gallery ("house", "envelope").</param>
public sealed record FluentIcon(int Code, string Name, string[] Tags)
{
    /// <summary>The glyph as stored in a view's or group's icon: the one character itself.</summary>
    public string Glyph { get; } = char.ConvertFromUtf32(Code);

    /// <summary>The name with its words spaced, for a tooltip: "Global Nav Button".</summary>
    public string DisplayName { get; } = FluentIcons.SpaceWords(Name);
}

/// <summary>[S-1801] An icon offered first, and the string that names it in every language.</summary>
public readonly record struct SuggestedIcon(int Code, Str Name);

/// <summary>
/// [S-1800] The whole Segoe Fluent Icons set, from the WinUI Gallery's list
/// (<c>FluentIconData.g.cs</c>, generated by <c>scripts/fluent-icons.py</c>), and the handful the
/// picker shows first.
/// </summary>
public static partial class FluentIcons
{
    private static Dictionary<string, FluentIcon>? _byGlyph;

    /// <summary>Every glyph, in code-point order.</summary>
    public static IReadOnlyList<FluentIcon> All => Data;

    /// <summary>
    /// [S-1801] The icons an area of the desktop is usually about, with a name in every language: shown
    /// first when nothing is typed, so the common choices stay one glance away in a set of 1,500, and
    /// searchable by that name in the user's language (the Gallery's names and tags are English).
    /// </summary>
    public static IReadOnlyList<SuggestedIcon> Suggested { get; } =
    [
        new(0xE80F, Str.Shell_Icon_Home), new(0xE821, Str.Shell_Icon_Work), new(0xE7FC, Str.Shell_Icon_Games),
        new(0xE8D6, Str.Shell_Icon_Music), new(0xE91B, Str.Shell_Icon_Photos), new(0xE714, Str.Shell_Icon_Video),
        new(0xE787, Str.Shell_Icon_Calendar), new(0xE715, Str.Shell_Icon_Mail), new(0xE716, Str.Shell_Icon_People),
        new(0xEB51, Str.Shell_Icon_Heart), new(0xE734, Str.Shell_Icon_Star), new(0xE7C1, Str.Shell_Icon_Flag),
        new(0xE718, Str.Shell_Icon_Pin), new(0xE8B7, Str.Shell_Icon_Folder), new(0xE8A5, Str.Shell_Icon_Document),
        new(0xE774, Str.Shell_Icon_Web), new(0xE943, Str.Shell_Icon_Code), new(0xEA80, Str.Shell_Icon_Ideas),
        new(0xE719, Str.Shell_Icon_Shopping), new(0xE917, Str.Shell_Icon_Time), new(0xE713, Str.Shell_Icon_Settings),
        new(0xE753, Str.Shell_Icon_Cloud), new(0xE9D2, Str.Shell_Icon_Charts), new(0xE8EC, Str.Shell_Icon_Tag),
        new(0xE8F1, Str.Shell_Icon_Library), new(0xE717, Str.Shell_Icon_Phone), new(0xE804, Str.Shell_Icon_Travel),
        new(0xE709, Str.Shell_Icon_Flights), new(0xE7BE, Str.Shell_Icon_Learning), new(0xE8D4, Str.Shell_Icon_Tasks),
        new(0xE77B, Str.Shell_Icon_Me), new(0xE945, Str.Shell_Icon_Lightning),
    ];

    /// <summary>
    /// [S-1802] The search over the whole set for <paramref name="locale"/>: the suggested icons
    /// lead and also match their name in that language and in English.
    /// </summary>
    public static IconSearch SearchFor(Locale locale)
    {
        var terms = new Dictionary<int, IReadOnlyList<string>>();
        foreach (var suggested in Suggested)
        {
            terms[suggested.Code] = [Strings.Get(locale, suggested.Name), Strings.Get(Locale.En, suggested.Name)];
        }

        return new IconSearch(Data, terms, [.. Suggested.Select(s => s.Code)]);
    }

    /// <summary>What a tooltip calls <paramref name="icon"/>: a suggested icon's name in <paramref name="locale"/>, else the spaced Gallery name.</summary>
    public static string NameFor(FluentIcon icon, Locale locale)
    {
        ArgumentNullException.ThrowIfNull(icon);
        foreach (var suggested in Suggested)
        {
            if (suggested.Code == icon.Code)
            {
                return Strings.Get(locale, suggested.Name);
            }
        }

        return icon.DisplayName;
    }

    /// <summary>The icon a stored glyph is, or null for none or one the set does not list.</summary>
    public static FluentIcon? ByGlyph(string? glyph)
    {
        if (string.IsNullOrEmpty(glyph))
        {
            return null;
        }

        _byGlyph ??= Data.ToDictionary(icon => icon.Glyph, StringComparer.Ordinal);
        return _byGlyph.TryGetValue(glyph, out var icon) ? icon : null;
    }

    /// <summary>"GlobalNavButton" to "Global Nav Button"; a run of capitals stays one word ("VPN", "OEMKey" to "OEM Key").</summary>
    internal static string SpaceWords(string name)
    {
        var builder = new StringBuilder(name.Length + 8);
        for (var i = 0; i < name.Length; i++)
        {
            var c = name[i];
            if (i > 0 && name[i - 1] != ' ' && c != ' ')
            {
                var previous = name[i - 1];
                var next = i + 1 < name.Length ? name[i + 1] : '\0';
                var lowerToUpper = char.IsUpper(c) && (char.IsLower(previous) || char.IsDigit(previous));
                var acronymEnd = char.IsUpper(c) && char.IsUpper(previous) && char.IsLower(next);
                var letterToDigit = char.IsDigit(c) && char.IsLetter(previous);
                if (lowerToUpper || acronymEnd || letterToDigit)
                {
                    builder.Append(' ');
                }
            }

            builder.Append(c);
        }

        return builder.ToString();
    }
}
